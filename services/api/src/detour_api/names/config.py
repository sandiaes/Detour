"""The configuration of name resolution: the steps of the hierarchy, their confidence, and which
steps each class of place may use. Everything that decides a name's rank is here, in one place.

Changing a value here changes what the app shows; bump ``NAMES_VERSION`` with it.
"""

from dataclasses import dataclass

NAMES_VERSION = "names-2026-11-14.1"

NAME_TYPES = (
    "original",
    "official_english",
    "established_english",
    "localized_brand",
    "official_romanization",
    "automatic_transliteration",
    "machine_translation",
    "search_alias",
    "user_override",
)

# Name types that were generated by Detour, not given by a source. The app labels them.
GENERATED_TYPES = frozenset({"automatic_transliteration", "machine_translation"})


@dataclass(frozen=True)
class Step:
    key: str
    confidence: float
    description: str


# The resolution hierarchy for an English interface, in order (the task brief of 2026-11-14).
# A step that has no name for a place is skipped. ``original`` always ends the list.
STEPS: tuple[Step, ...] = (
    Step("user_override", 1.00, "The name the user approved for this place"),
    Step("provider_official_en", 0.99, "An English name the place's provider marks as official"),
    Step("wikidata_label_en", 0.98, "The English label of the place's Wikidata item"),
    Step("enwiki_title", 0.97, "The title of the item's English Wikipedia article"),
    Step("osm_name_en", 0.93, "OpenStreetMap name:en"),
    Step("osm_official_name_en", 0.85, "OpenStreetMap official_name:en"),
    Step("osm_brand_en", 0.85, "OpenStreetMap brand:en (an English brand name)"),
    Step("osm_short_name_en", 0.85, "OpenStreetMap short_name:en"),
    Step("osm_int_name", 0.85, "OpenStreetMap int_name, only when written in Latin letters"),
    Step("provider_romanization", 0.85, "A romanized name the source gives (name:ja-Latn, ...)"),
    Step("transliteration_specific", 0.70, "A language-specific transliteration Detour made"),
    Step("machine_translation", 0.50, "Never produced; reserved and off by default"),
    Step("transliteration_generic", 0.35, "A generic transliteration Detour made (last resort)"),
    Step("original", 1.00, "The original local name (a reliable name, though not English)"),
)
STEP_BY_KEY = {s.key: s for s in STEPS}
STEP_ORDER = {s.key: i for i, s in enumerate(STEPS)}

# Confidence of names that are not display candidates (search aliases from Wikidata).
ALIAS_CONFIDENCE = 0.60

# Machine translation is never produced by Detour (no provider, no model). A stored machine
# translation would still be ignored unless this is switched on.
ALLOW_MACHINE_TRANSLATION = False

# Two English candidates at or above this confidence that disagree are a conflict: the alternative
# is kept as an alias and the conflict is logged.
CONFLICT_THRESHOLD = 0.90

_ALL = tuple(s.key for s in STEPS)
# Steps each class of place may use (same order as STEPS). Businesses keep their own name: only an
# official English name, an English brand name or an international name (in Latin letters) replaces
# it; never a Wikidata or Wikipedia name, a mapper's name:en (usually a translation), a
# romanization or a transliteration (those stay searchable as aliases).
CLASS_STEPS: dict[str, tuple[str, ...]] = {
    "landmark": _ALL,
    "natural": _ALL,
    "settlement": _ALL,
    "transport": tuple(k for k in _ALL if k not in ("transliteration_generic", "osm_brand_en")),
    "business": (
        "user_override",
        "provider_official_en",
        "osm_official_name_en",
        "osm_brand_en",
        "osm_int_name",
        "original",
    ),
    "street": ("user_override", "provider_official_en", "osm_official_name_en", "original"),
}

# The class of a geo.place by kind and category. A category that is not listed is a landmark.
BUSINESS_CATEGORIES = frozenset(
    {"restaurant", "cafe", "fast_food", "bar", "pub", "hotel", "hostel", "guest_house", "shop"}
)
TRANSPORT_CATEGORIES = frozenset({"station", "airport", "aerodrome", "ferry_terminal", "halt"})
NATURAL_CATEGORIES = frozenset({"peak", "volcano", "waterfall", "lake", "glacier", "cave_entrance"})


def place_class(kind: str | None, category: str | None) -> str:
    if kind in ("city", "area", "country"):
        return "settlement"
    if kind == "restaurant" or (category or "") in BUSINESS_CATEGORIES:
        return "business"
    if (category or "") in TRANSPORT_CATEGORIES or kind == "transport_hub":
        return "transport"
    if (category or "") in NATURAL_CATEGORIES:
        return "natural"
    if kind == "street":
        return "street"
    return "landmark"


# Stored Wikidata and Wikipedia names expire after this many days unless something in the app
# (an itinerary item, a past-trip visit, a trip's city) still names the place.
STORED_NAME_DAYS = 90
# "No English name" answers are asked again after this many days (negative cache).
NEGATIVE_RETRY_DAYS = 90
# At most this many Wikidata aliases are kept per item and language (for search).
MAX_ALIASES = 5
